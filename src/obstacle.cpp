Obstacle::Obstacle(Vector2 position): position(position){
    for (unsigned int row = 0; row < grid.size(); row++){
        for (unsigned int col = 0; col < grid[0].size(); col++){
            if(grid[row][col] == 1){
                float blockPosX = position.x + (col * 3);
                float blockPosY = position.y + (row * 3);

                Block block = Block({blockPosX, blockPosY});

                blocks.push_back(block);
            }
        }
    }
}

void Obstacle::Draw(){
    for (auto& block: blocks){
        block.Draw();
    }
}
